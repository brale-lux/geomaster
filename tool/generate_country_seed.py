#!/usr/bin/env python3
"""Generate the idempotent country-catalog seed migration from the canonical v1.3 allowlist.

    python3 -I tool/generate_country_seed.py

Reads  assets/data/GeoMaster_Country_Catalog_195_v1.3.json
Writes supabase/migrations/20261116000750_seed_country_catalog.sql
The JSON is the source of truth (spec v1.3 A3); regenerate rather than hand-editing the SQL.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets/data/GeoMaster_Country_Catalog_195_v1.3.json"
OUT = ROOT / "supabase/migrations/20261116000750_seed_country_catalog.sql"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main():
    raw = SRC.read_bytes()
    data = json.loads(raw.decode("utf-8"))
    rows = data["countries"]
    iso2 = [r["iso2"] for r in rows]
    iso3 = [r["iso3"] for r in rows]
    names = [r["name"] for r in rows]
    problems = []
    if len(rows) != 195:
        problems.append(f"expected 195 countries, found {len(rows)}")
    for label, vals in (("iso2", iso2), ("iso3", iso3), ("name", names)):
        if len(set(vals)) != len(vals):
            problems.append(f"duplicate {label}")
    if sum(r["status"] == "un_member" for r in rows) != 193 or sum(r["status"] == "un_observer" for r in rows) != 2:
        problems.append("expected 193 un_member + 2 un_observer")
    if not all(re.fullmatch(r"[A-Z]{2}", a) and re.fullmatch(r"[A-Z]{3}", b) for a, b in zip(iso2, iso3)):
        problems.append("bad ISO code")
    if {"VA", "PS"} - set(iso2):
        problems.append("Holy See (VA) and State of Palestine (PS) must both be present")
    if {"TW", "XK"} & set(iso2):
        problems.append("Taiwan/Kosovo must not be in the 195 denominator (spec v1.3 A3)")
    if problems:
        sys.exit("Country catalog invalid: " + "; ".join(problems))

    sha = hashlib.sha256(raw).hexdigest()
    version = "country-catalog-v" + str(data.get("version", "1.3"))
    values = ",\n".join(
        f"  ({q(r['iso2'])}, {q(r['iso3'])}, {q(r['name'])}, {q(r['status'])})" for r in rows)
    sql = f"""-- GeoMaster 0750: the 195-country allowlist (GENERATED by tool/generate_country_seed.py; do not edit).
-- Source: assets/data/{SRC.name} (sha256 {sha}).
-- Definition: {data.get('definition')}. Content-scope convention per spec v1.3 A3, not a judgement on
-- sovereignty or disputed status. Display names may change; ISO 3166-1 codes are the stable keys.

insert into public.country_catalog_versions
  (version_key, definition, source_filename, source_sha256, country_count, provenance_note)
values ({q(version)}, {q(data.get('definition', ''))}, {q(SRC.name)}, {q(sha)}, 195,
        'Supplied with the GeoMaster v1.3 development package. Holy See uses VA/VAT and State of Palestine '
        'uses PS/PSE (ISO 3166-1). Map shapes not yet licensed.')
on conflict (version_key) do nothing;

insert into public.country_catalog (iso2, iso3, name, un_status, catalog_version_id)
select v.iso2, v.iso3, v.name, v.un_status, cv.id
from (values
{values}
) as v(iso2, iso3, name, un_status)
cross join public.country_catalog_versions cv
where cv.version_key = {q(version)}
on conflict (iso2) do update set
  iso3 = excluded.iso3, name = excluded.name, un_status = excluded.un_status,
  catalog_version_id = excluded.catalog_version_id;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows)} countries, sha256 {sha[:12]}…)")


if __name__ == "__main__":
    main()
