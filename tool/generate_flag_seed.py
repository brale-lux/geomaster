#!/usr/bin/env python3
"""Generate the flag seed migration from assets/flags/MANIFEST.json (written by tool/fetch_flags.py).

    python3 -I tool/generate_flag_seed.py
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "assets/flags/MANIFEST.json"
CATALOG = ROOT / "assets/data/GeoMaster_Country_Catalog_195_v1.3.json"
OUT = ROOT / "supabase/migrations/20261116000770_seed_country_flags.sql"
NOTES = {"AF": "Islamic Republic tricolour (2013–2021), as flown at the UN; chosen by the owner over the Taliban flag."}


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def main():
    m = json.loads(MANIFEST.read_text(encoding="utf-8"))
    isos = {c["iso2"] for c in json.loads(CATALOG.read_text(encoding="utf-8"))["countries"]}
    problems = sorted(isos - set(m)) + [f"extra {k}" for k in sorted(set(m) - isos)]
    rows = []
    for iso, e in sorted(m.items()):
        f = ROOT / f"assets/flags/{iso.lower()}.svg"
        if not f.exists() or hashlib.sha256(f.read_bytes()).hexdigest() != e["sha256"]:
            problems.append(f"{iso}: file missing or checksum differs from manifest")
            continue
        restr = [r for r in (e.get("restrictions") or "").split("|") if r]
        arr = "array[" + ", ".join(q(r) for r in restr) + "]::text[]" if restr else "'{}'::text[]"
        rows.append(f"  ({q(iso)}, {q(f'assets/flags/{iso.lower()}.svg')}, {q(e['sha256'])}, {e['aspect_ratio']}, "
                    f"{q(e['commons_title'])}, {q(e['source_url'])}, {q(e['license'])}, {q(e.get('license_url'))}, "
                    f"{q(e.get('artist'))}, {arr}, {q(NOTES.get(iso))})")
    if problems:
        sys.exit("Flag manifest invalid: " + "; ".join(problems))
    sql = f"""-- GeoMaster 0770: country flags from Wikimedia Commons (GENERATED by tool/generate_flag_seed.py; do not edit).
-- Licence, author and restriction tags are per file; 'insignia' means national-symbol rules may apply.

insert into public.country_flag_assets (country_iso2, bundle_path, sha256, aspect_ratio, commons_title, source_url,
                                        license, license_url, artist, restrictions, note)
values
{(',' + chr(10)).join(rows)}
on conflict (country_iso2) do update set
  bundle_path = excluded.bundle_path, sha256 = excluded.sha256, aspect_ratio = excluded.aspect_ratio,
  commons_title = excluded.commons_title, source_url = excluded.source_url, license = excluded.license,
  license_url = excluded.license_url, artist = excluded.artist, restrictions = excluded.restrictions,
  note = excluded.note;

update public.country_catalog c set flag_asset_path = f.bundle_path, flag_asset_status = 'sourced'
from public.country_flag_assets f
where f.country_iso2 = c.iso2 and c.flag_asset_path is distinct from f.bundle_path;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows)} flags)")


if __name__ == "__main__":
    main()
